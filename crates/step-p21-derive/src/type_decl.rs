use inflector::Inflector;
use proc_macro_error2::ResultExt;
use proc_macro2::TokenStream as TokenStream2;
use quote::{format_ident, quote};

use crate::holder_codegen;

use super::{FieldType, HolderAttr, as_holder_ident, step_p21_crate};

pub fn derive_holder(
    ident: &syn::Ident,
    st: &syn::DataStruct,
    attr: &HolderAttr,
) -> TokenStream2 {
    let name = ident.to_string().to_screaming_snake_case();
    let holder_ident = as_holder_ident(ident);
    let def_holder_tt = def_holder(ident, st);
    let impl_holder_tt = impl_holder(ident, attr, st);
    let impl_entity_table_tt = holder_codegen::impl_entity_table(ident, attr);
    if attr.generate_deserialize {
        let def_visitor_tt = def_visitor(&holder_ident, &name, st);
        let impl_deserialize_tt = impl_deserialize(&holder_ident, &name, st);
        let impl_with_visitor_tt = holder_codegen::impl_with_visitor(ident);
        quote! {
            #def_holder_tt
            #impl_holder_tt
            #impl_entity_table_tt
            #def_visitor_tt
            #impl_deserialize_tt
            #impl_with_visitor_tt
        }
    } else {
        quote! {
            #def_holder_tt
            #impl_holder_tt
            #impl_entity_table_tt
        }
    }
}

pub fn def_holder(ident: &syn::Ident, st: &syn::DataStruct) -> TokenStream2 {
    let holder_ident = as_holder_ident(ident);
    let FieldEntries { holder_types, .. } = FieldEntries::parse(st);
    quote! {
        /// Auto-generated by `#[derive(Holder)]`
        #[derive(Debug, Clone, PartialEq)]
        pub struct #holder_ident(#(pub #holder_types),*);
    }
}

pub fn impl_holder(
    ident: &syn::Ident,
    table: &HolderAttr,
    st: &syn::DataStruct,
) -> TokenStream2 {
    let name = ident.to_string().to_screaming_snake_case();
    let holder_ident = as_holder_ident(ident);
    let FieldEntries {
        holder_types,
        into_owned,
    } = FieldEntries::parse(st);
    let HolderAttr { table, .. } = table;
    let tuple_len = holder_types.len();
    let table_arg = holder_codegen::table_arg();
    let step_p21 = step_p21_crate();

    quote! {
        #[automatically_derived]
        impl #step_p21::tables::IntoOwned for #holder_ident {
            type Table = #table;
            type Owned = #ident;
            fn into_owned(self, #table_arg: &Self::Table) -> #step_p21::error::Result<Self::Owned> {
                Ok(#ident ( #(#into_owned),* ))
            }
        }
        #[automatically_derived]
        impl #step_p21::tables::Holder for #holder_ident {
            fn name() -> &'static str {
                #name
            }
            fn attr_len() -> usize {
                #tuple_len
            }
        }
    } // quote!
}

fn def_visitor(
    ident: &syn::Ident,
    name: &str,
    st: &syn::DataStruct,
) -> TokenStream2 {
    let count = st.fields.len();
    let attributes = (0..count)
        .map(|i| format_ident!("a_{}", i))
        .collect::<Vec<_>>();
    let construct = quote! { #ident (#(#attributes),*) };
    holder_codegen::def_visitor(ident, name, &attributes, &construct)
}

fn impl_deserialize(
    ident: &syn::Ident,
    name: &str,
    st: &syn::DataStruct,
) -> TokenStream2 {
    holder_codegen::impl_deserialize(ident, name, st.fields.len())
}

struct FieldEntries {
    holder_types: Vec<syn::Type>,
    into_owned: Vec<TokenStream2>,
}

impl FieldEntries {
    fn parse(st: &syn::DataStruct) -> Self {
        let table_arg = holder_codegen::table_arg();

        let mut holder_types = Vec::new();
        let mut into_owned = Vec::new();

        for (i, field) in st.fields.iter().enumerate() {
            let ft: FieldType = field
                .ty
                .clone()
                .try_into()
                .expect_or_abort("unsupported declared field type");
            let index = syn::Index::from(i);

            let HolderAttr { place_holder, .. } =
                HolderAttr::parse(&field.attrs);
            if place_holder {
                into_owned.push(holder_codegen::into_owned_value(
                    &ft,
                    quote!(self.#index),
                    &table_arg,
                ));
                holder_types.push(ft.into_holder().into_place_holder().into());
            } else {
                into_owned.push(quote! { self.#index });
                holder_types.push(ft.into());
            }
        }
        Self {
            holder_types,
            into_owned,
        }
    }
}
